import { STATES } from '../audio/states';
import { buildId3Tag, type AudioTags } from './id3';
import type { ExportSelection } from './offlineRenderer';
import { exportMime, type ExportFormat } from './options';
import { WAV_HEADER_BYTES, wavInfoChunk } from './wav';

/**
 * What an exported file says about itself in a player: the label as the
 * title, Resonance as the artist, the state as the album, and a one-line
 * description of the sound as the comment.
 */
export function exportTags(sel: ExportSelection, label: string): AudioTags {
  const p = sel.profile;
  const parts: string[] = [`${Math.round(sel.durationSec / 60)} min`];
  if (sel.program) parts.push(`program “${sel.program.name}”`);
  if (p.noise.enabled) parts.push(`${p.noise.type} noise`);
  if (p.binaural.enabled) parts.push(`${Math.round(p.binaural.beat * 10) / 10} Hz beat`);
  if (p.ambience.enabled) parts.push(p.ambience.type);
  if (p.harmony.enabled) parts.push('harmonic pad');
  return {
    title: label,
    artist: 'Resonance',
    album: STATES[sel.state].label,
    genre: 'Ambient',
    comment: `${parts.join(' · ')}. Generated by Resonance — not a medical device.`,
  };
}

/**
 * Tag a finished file: MP3 gets an ID3v2.3 tag prepended (lamejs writes
 * none); WAV gets a LIST/INFO chunk appended, with the RIFF size in the
 * header grown to match. The encoded audio itself is never copied.
 */
export async function tagExport(blob: Blob, format: ExportFormat, tags: AudioTags): Promise<Blob> {
  const type = exportMime(format);
  if (format === 'mp3') return new Blob([buildId3Tag(tags) as BlobPart, blob], { type });
  const info = wavInfoChunk({
    INAM: tags.title,
    IART: tags.artist,
    IPRD: tags.album,
    IGNR: tags.genre,
    ICMT: tags.comment,
  });
  const header = new Uint8Array(await blob.slice(0, WAV_HEADER_BYTES).arrayBuffer());
  const view = new DataView(header.buffer);
  view.setUint32(4, view.getUint32(4, true) + info.length, true);
  return new Blob([header as BlobPart, blob.slice(WAV_HEADER_BYTES), info as BlobPart], { type });
}
