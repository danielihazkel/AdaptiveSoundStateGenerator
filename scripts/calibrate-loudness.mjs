// Measures every personalizer arm's loudness in a real browser and writes
// src/audio/loudnessTable.ts — the per-arm trims that make each variation of
// a state play at that state's default loudness (Phase 13). Run after adding
// or changing a recipe in src/personalization/candidates.ts:
//
//   npm run calibrate:loudness
//
// Renders go through the real engine on OfflineAudioContexts via the dev-only
// QA hooks (src/dev/qaHooks.ts). The noise generators are random, so repeat
// measurements wobble by ~0.2 LU; trims are rounded to 0.5 dB, about the
// smallest loudness step a listener notices.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';

const PORT = 5318;
const INTENSITIES = [0, 0.5, 1];
const MIN_DB = -9;
const MAX_DB = 3;
const out = fileURLToPath(new URL('../src/audio/loudnessTable.ts', import.meta.url));

const server = await createServer({ server: { port: PORT, strictPort: true }, logLevel: 'warn' });
await server.listen();
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
try {
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error('[pageerror]', e.message));
  await page.goto(`http://localhost:${PORT}/?qa`);
  await page.waitForFunction(() => window.__qa !== undefined, undefined, { timeout: 60_000 });
  console.log('Measuring every arm × intensity (a few minutes)…');
  const lufs = await page.evaluate(
    (intensities) => window.__qa.measureArms({ seconds: 24, intensities }),
    INTENSITIES,
  );

  const round = (db) => Math.round(db * 2) / 2 || 0; // 0.5 dB steps, no -0
  const trims = {};
  for (const [state, arms] of Object.entries(lufs)) {
    trims[state] = {};
    const prior = arms.prior;
    for (const [arm, values] of Object.entries(arms)) {
      trims[state][arm] =
        arm === 'prior'
          ? INTENSITIES.map(() => 0)
          : values.map((v, i) => Math.min(MAX_DB, Math.max(MIN_DB, round(prior[i] - v))));
      const report = values.map((v, i) => `${v.toFixed(1)}→${trims[state][arm][i]}`).join('  ');
      console.log(`${state.padEnd(10)} ${arm.padEnd(14)} ${report}`);
    }
  }

  // One arm per line: `"beat-down": [0, 0.5, 0],`
  const body = JSON.stringify(trims, null, 2).replace(/\[\s+([^\]]*?)\s+\]/g, (_, inner) =>
    `[${inner.split(/,\s*/).join(', ')}]`,
  );
  writeFileSync(
    out,
    [
      '// GENERATED by scripts/calibrate-loudness.mjs — do not edit by hand.',
      `// Measured ${new Date().toISOString().slice(0, 10)}: BS.1770 integrated loudness of each arm`,
      '// (24 s steady render — at least two periods of the slowest, breathing-rate pulse — stereo, masterVolume 0.5), trimmed to its state prior.',
      '',
      '/** Intensities the trims below are measured at; values interpolate linearly between. */',
      `export const LOUDNESS_TABLE_INTENSITIES = ${JSON.stringify(INTENSITIES)} as const;`,
      '',
      '/** state → arm → trim in dB at each LOUDNESS_TABLE_INTENSITIES point. */',
      `export const LOUDNESS_TABLE: Record<string, Record<string, readonly number[]>> = ${body};`,
      '',
    ].join('\n'),
  );
  console.log(`Wrote ${out}`);
} finally {
  await browser.close();
  await server.close();
}
